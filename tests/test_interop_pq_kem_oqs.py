"""Interop tests between our Python PQ KEM wrappers and liboqs.

GIVEN a key generated by keyutils-py,
WHEN encapsulation/decapsulation is performed in either implementation,
THEN the shared secrets must agree.
"""

import unittest

from keyutils_py import generate_key
from keyutils_py.utils import OQS_AVAILABLE, oqs


_ALGORITHMS = (
    "ml-kem-512",
    "ml-kem-768",
    "ml-kem-1024",
    "frodokem-976-shake",
    "frodokem-976-aes",
    "frodokem-1344-shake",
    "frodokem-1344-aes",
)


@unittest.skipUnless(OQS_AVAILABLE, "liboqs is not installed; interop tests skipped")
class TestPQKEMInteropWithOQS(unittest.TestCase):
    """Cross-check our PQ KEM wrappers against the underlying liboqs.

    Two directions per algorithm:

    1. Python public key -> encaps; ciphertext -> oqs decap (Python private bytes
       form the oqs secret key).
    2. oqs encaps against the Python public key -> Python private key decap.
    """

    def _private_bytes(self, key) -> bytes:
        """Retrieve the raw expanded private-key bytes for an algorithm."""
        if hasattr(key, "private_bytes_raw"):
            try:
                return key.private_bytes_raw()  # type: ignore[call-arg]
            except Exception:
                pass
        return key._private_key_bytes  # type: ignore[attr-defined]

    def test_python_encaps_oqs_decaps(self):
        """GIVEN a Python key / WHEN Python encapsulates / THEN oqs decapsulates the same secret."""
        for name in _ALGORITHMS:
            with self.subTest(algorithm=name):
                key = generate_key(name)
                pub = key.public_key()
                oqs_name = key._other_name  # type: ignore[attr-defined]
                priv_bytes = self._private_bytes(key)

                ss_py, ct = pub.encaps()

                oqs_priv = oqs.KeyEncapsulation(oqs_name, secret_key=priv_bytes)
                ss_oqs = oqs_priv.decap_secret(ct)

                self.assertEqual(ss_py, ss_oqs)

    def test_oqs_encaps_python_decaps(self):
        """GIVEN a Python key / WHEN oqs encapsulates / THEN Python decapsulates the same secret."""
        for name in _ALGORITHMS:
            with self.subTest(algorithm=name):
                key = generate_key(name)
                pub = key.public_key()
                pub_bytes = pub.public_bytes_raw()
                oqs_name = key._other_name  # type: ignore[attr-defined]

                oqs_pub = oqs.KeyEncapsulation(oqs_name)
                ct_oqs, ss_oqs = oqs_pub.encap_secret(pub_bytes)

                ss_py = key.decaps(ct_oqs)

                self.assertEqual(ss_py, ss_oqs)


if __name__ == "__main__":
    unittest.main()
