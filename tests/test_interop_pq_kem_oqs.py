"""Interop tests between our Python PQ KEM implementations and liboqs.

GIVEN a key pair generated by either implementation,
WHEN encapsulation/decapsulation is performed in either implementation,
THEN the shared secrets must agree.
"""

import unittest

from keyutils_py import generate_key
from keyutils_py.fips.frodokem import FrodoKEM
from keyutils_py.oids import FRODOKEM_NAME_2_OID
from keyutils_py.utils import OQS_AVAILABLE, oqs


_ML_KEM_ALGORITHMS = (
    "ml-kem-512",
    "ml-kem-768",
    "ml-kem-1024",
)

# Every FrodoKEM variant that has an OID, as the bundled implementation and liboqs name it
# (``frodokem-976-shake`` -> ``FrodoKEM-976-SHAKE``).
_FRODOKEM_VARIANTS = tuple(sorted(name.upper().replace("FRODOKEM", "FrodoKEM") for name in FRODOKEM_NAME_2_OID))
_KEY_GENERATORS = ("oqs", "python")


@unittest.skipUnless(OQS_AVAILABLE, "liboqs is not installed; interop tests skipped")
class TestPQKEMInteropWithOQS(unittest.TestCase):
    """Cross-check our ML-KEM wrappers against the underlying liboqs.

    Two directions per algorithm:

    1. Python public key -> encaps; ciphertext -> oqs decap (Python private bytes
       form the oqs secret key).
    2. oqs encaps against the Python public key -> Python private key decap.
    """

    def _private_bytes(self, key) -> bytes:
        """Retrieve the raw expanded private-key bytes for an algorithm."""
        if hasattr(key, "private_bytes_raw"):
            try:
                return key.private_bytes_raw()  # type: ignore[call-arg]
            except Exception:
                pass
        return key._private_key_bytes  # type: ignore[attr-defined]

    def test_python_encaps_oqs_decaps(self):
        """GIVEN a Python key / WHEN Python encapsulates / THEN oqs decapsulates the same secret."""
        for name in _ML_KEM_ALGORITHMS:
            with self.subTest(algorithm=name):
                key = generate_key(name)
                pub = key.public_key()
                oqs_name = key._other_name  # type: ignore[attr-defined]
                priv_bytes = self._private_bytes(key)

                ss_py, ct = pub.encaps()

                oqs_priv = oqs.KeyEncapsulation(oqs_name, secret_key=priv_bytes)
                ss_oqs = oqs_priv.decap_secret(ct)

                self.assertEqual(ss_py, ss_oqs)

    def test_oqs_encaps_python_decaps(self):
        """GIVEN a Python key / WHEN oqs encapsulates / THEN Python decapsulates the same secret."""
        for name in _ML_KEM_ALGORITHMS:
            with self.subTest(algorithm=name):
                key = generate_key(name)
                pub = key.public_key()
                pub_bytes = pub.public_bytes_raw()
                oqs_name = key._other_name  # type: ignore[attr-defined]

                oqs_pub = oqs.KeyEncapsulation(oqs_name)
                ct_oqs, ss_oqs = oqs_pub.encap_secret(pub_bytes)

                ss_py = key.decaps(ct_oqs)

                self.assertEqual(ss_py, ss_oqs)


@unittest.skipUnless(OQS_AVAILABLE, "liboqs is not installed; interop tests skipped")
class TestFrodoKEMInteropWithOQS(unittest.TestCase):
    """Cross-check the bundled pure-Python FrodoKEM against liboqs.

    The FrodoKEM key classes switch to liboqs for encapsulation and decapsulation as soon as it is
    installed, so going through them would let liboqs talk to itself. These tests call the two
    implementations directly: ``keyutils_py.fips.frodokem.FrodoKEM`` and ``oqs.KeyEncapsulation``.
    Every check runs with a key pair from liboqs and with one from the Python code.
    """

    @staticmethod
    def _generate_key_pair(variant: str, generator: str) -> tuple[bytes, bytes]:
        """Return ``(public_key, secret_key)`` generated by liboqs or by the Python code."""
        if generator == "python":
            return FrodoKEM(variant).kem_keygen()
        kem = oqs.KeyEncapsulation(variant)
        public_key = kem.generate_keypair()
        return public_key, kem.export_secret_key()

    def test_key_generation(self):
        """GIVEN a FrodoKEM variant / WHEN liboqs and the Python code generate a key pair / THEN both have its layout.

        The secret key is ``s || seedA || b || S^T || pkh``, so it embeds the public key ``seedA || b``
        right after ``s``.
        """
        for variant in _FRODOKEM_VARIANTS:
            params = FrodoKEM(variant)
            for generator in _KEY_GENERATORS:
                with self.subTest(variant=variant, generator=generator):
                    public_key, secret_key = self._generate_key_pair(variant, generator)
                    self.assertEqual(len(public_key), params.len_pk_bytes)
                    self.assertEqual(len(secret_key), params.len_sk_bytes)
                    embedded = secret_key[params.len_s_bytes : params.len_s_bytes + params.len_pk_bytes]
                    self.assertEqual(embedded, public_key)

    def test_oqs_encaps_python_decaps(self):
        """GIVEN a key pair from either implementation / WHEN liboqs encapsulates / THEN Python decapsulates it."""
        for variant in _FRODOKEM_VARIANTS:
            for generator in _KEY_GENERATORS:
                with self.subTest(variant=variant, generator=generator):
                    public_key, secret_key = self._generate_key_pair(variant, generator)

                    ct, ss_oqs = oqs.KeyEncapsulation(variant).encap_secret(public_key)
                    ss_py = FrodoKEM(variant).kem_decaps(secret_key, ct)

                    self.assertEqual(ss_py, ss_oqs)

    def test_python_encaps_oqs_decaps(self):
        """GIVEN a key pair from either implementation / WHEN Python encapsulates / THEN liboqs decapsulates it."""
        for variant in _FRODOKEM_VARIANTS:
            for generator in _KEY_GENERATORS:
                with self.subTest(variant=variant, generator=generator):
                    public_key, secret_key = self._generate_key_pair(variant, generator)

                    ct, ss_py = FrodoKEM(variant).kem_encaps(public_key)
                    ss_oqs = oqs.KeyEncapsulation(variant, secret_key=secret_key).decap_secret(ct)

                    self.assertEqual(ss_oqs, ss_py)


if __name__ == "__main__":
    unittest.main()
