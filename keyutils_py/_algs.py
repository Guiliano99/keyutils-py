# Indexes. The first row wins where a key occurs twice (the two HMAC-SHA1 OIDs), hence ``reversed``.
KDF_BY_OID: Mapping[univ.ObjectIdentifier, KdfRow] = MappingProxyType({row.oid: row for row in KDF_ROWS})
KDF_OID: Mapping[Tuple[str, Optional[str]], univ.ObjectIdentifier] = MappingProxyType(
    {(row.family, row.hash): row.oid for row in reversed(KDF_ROWS)}
)
MAC_BY_OID: Mapping[univ.ObjectIdentifier, MacRow] = MappingProxyType({row.oid: row for row in MAC_ROWS})
MAC_OID: Mapping[Tuple[str, Optional[str], Optional[int]], univ.ObjectIdentifier] = MappingProxyType(
    {(row.family, row.hash, row.bits): row.oid for row in reversed(MAC_ROWS)}
)
PRF_OID: Mapping[str, univ.ObjectIdentifier] = MappingProxyType(
    {row.hash: row.oid for row in MAC_ROWS if row.family == "hmac" and row.hash is not None and row.prf}
)
WRAP_BY_OID: Mapping[univ.ObjectIdentifier, WrapRow] = MappingProxyType({row.oid: row for row in WRAP_ROWS})
WRAP_OID: Mapping[Tuple[str, int], univ.ObjectIdentifier] = MappingProxyType(
    {(row.mode, row.kek_len): row.oid for row in WRAP_ROWS}
)
CONTENT_BY_OID: Mapping[univ.ObjectIdentifier, ContentRow] = MappingProxyType({row.oid: row for row in CONTENT_ROWS})
CONTENT_OID: Mapping[Tuple[str, int], univ.ObjectIdentifier] = MappingProxyType(
    {(row.mode, row.key_len): row.oid for row in CONTENT_ROWS}
)
KARI_BY_OID: Mapping[univ.ObjectIdentifier, KariRow] = MappingProxyType({row.oid: row for row in KARI_ROWS})
KT_BY_OID: Mapping[univ.ObjectIdentifier, KtRow] = MappingProxyType({row.oid: row for row in KT_ROWS})
