"""The algorithm tables: one literal tuple of rows per fact, and the indexes derived from it.

What an OID of a key derivation function, MAC, key wrap, content encryption, key agreement scheme or key transport
algorithm stands for is written here and nowhere else. A row names its facts as structured fields (a family, a hash by
the name of the hash registry, a size), so no code splits a name to find them. The inverse indexes are generated by a
comprehension at import and never typed by hand.

Adding a member of a known family (a hash for HKDF, an AES size) is one row here, one row in
``tests/golden/alg_tables.tsv`` (written from the RFCs by ``tests/golden/generate_alg_tables.py``) and a CHANGELOG
line. The key agreement and key transport rows are data only: the functions that read them are separate.
"""

from dataclasses import dataclass
from types import MappingProxyType
from typing import Any, Dict, Mapping, NamedTuple, Optional, Tuple

from pyasn1.type import univ
from pyasn1_alt_modules import (
    rfc3370,
    rfc3565,
    rfc5084,
    rfc5649,
    rfc5753,
    rfc5990,
    rfc8017,
    rfc8018,
    rfc8410,
    rfc8619,
    rfc9481,
    rfc9688,
)


class AlgInfo(NamedTuple):
    """What the package knows about one algorithm OID, as :func:`keyutils_py.list_algorithms` returns it.

    ``params`` holds the keywords that :func:`keyutils_py.make_alg_id` takes for this row and that the row fixes
    (for example ``{"hash": "sha256"}`` for HKDF or ``{"bits": 256, "mode": "kwp"}`` for a key wrap).
    """

    kind: str
    family: str
    params: Mapping[str, Any]
    oid: univ.ObjectIdentifier


@dataclass(frozen=True)
class KdfRow:
    """A key derivation function.

    ``hash`` is the hash of HKDF, which is part of the OID. KDF2 and KDF3 carry their hash in the parameters
    (RFC 9690 Appendix B), PBKDF2 its pseudorandom function (RFC 8018 Appendix A.2), so both have no hash here.
    """

    oid: univ.ObjectIdentifier
    family: str  # "hkdf", "kdf2", "kdf3" or "pbkdf2"
    hash: Optional[str]

    def info(self) -> AlgInfo:
        """Return the listing row."""
        return AlgInfo("kdf", self.family, {} if self.hash is None else {"hash": self.hash}, self.oid)


@dataclass(frozen=True)
class MacRow:
    """A message authentication code.

    ``hash`` is the hash of HMAC and the SHAKE function of KMAC, ``bits`` the AES key size of AES-GMAC.
    ``prf`` marks an HMAC OID that RFC 8018 Appendix B.1 names as a pseudorandom function of PBKDF2: the form that
    a PBKDF2 identifier is written with. SHA-1 has two HMAC OIDs: the first row is the one written for a MAC.
    """

    oid: univ.ObjectIdentifier
    family: str  # "hmac", "kmac", "gmac" or "pbmac1"
    hash: Optional[str]
    bits: Optional[int]
    prf: bool = False

    def info(self) -> AlgInfo:
        """Return the listing row."""
        params: Dict[str, Any] = {}
        if self.hash is not None:
            params["hash"] = self.hash
        if self.bits is not None:
            params["bits"] = self.bits
        return AlgInfo("mac", self.family, params, self.oid)


@dataclass(frozen=True)
class WrapRow:
    """An AES key wrap: RFC 3394 (``kw``) or RFC 5649 with padding (``kwp``). ``kek_len`` is in octets."""

    oid: univ.ObjectIdentifier
    mode: str  # "kw" or "kwp"
    kek_len: int

    def info(self) -> AlgInfo:
        """Return the listing row."""
        return AlgInfo("wrap", "aes", {"bits": self.kek_len * 8, "mode": self.mode}, self.oid)


@dataclass(frozen=True)
class ContentRow:
    """An AES content encryption: CBC with PKCS#7 padding (RFC 3565) or GCM (RFC 5084). ``key_len`` is in octets."""

    oid: univ.ObjectIdentifier
    mode: str  # "cbc" or "gcm"
    key_len: int

    def info(self) -> AlgInfo:
        """Return the listing row."""
        return AlgInfo("content", f"aes-{self.mode}", {"bits": self.key_len * 8}, self.oid)


@dataclass(frozen=True)
class KariRow:
    """A key agreement scheme of ``KeyAgreeRecipientInfo`` (RFC 5753), with the hash of its KDF.

    ``legacy`` rows (``id-X25519``, ``id-X448``, ``id-alg-ESDH``) name no hash; the row keeps the SHA-256 of the
    X9.63 KDF that the callers of this package used with them.
    """

    oid: univ.ObjectIdentifier
    kind: str  # "stdDH", "cofactorDH", "mqv" or "legacy"
    hash: str


@dataclass(frozen=True)
class KtRow:
    """A key transport algorithm of ``KeyTransRecipientInfo``: RSAES-PKCS1-v1_5 or RSAES-OAEP."""

    oid: univ.ObjectIdentifier
    padding: str  # "pkcs1v15" or "oaep"


